def _lic(x: Any) -> str:
    return x if x else "none declared"


def obligations(report: dict) -> list[tuple[str, str, str]]:
    """(license, clause code, obligation) for every lien, in report order, without repeats."""
    out, seen = [], set()
    for lien in report.get("liens") or []:
        for c in lien.get("clauses") or []:
            key = (lien.get("license"), c.get("code"))
            if key in seen:
                continue
            seen.add(key)
            out.append((lien.get("license", "?"), c.get("code", "?"), c.get("obligation", "")))
    return out


def upstream_terms(report: dict) -> str:
    """Short 'gemma via google/gemma-3-27b-pt' style description of inherited liens."""
    parts = []
    for lien in report.get("liens") or []:
        if lien.get("depth", 0) == 0:
            parts.append(f"{lien.get('license')} (declared on the model itself)")
        else:
            parts.append(f"{lien.get('license')} via {lien.get('via')} (depth {lien.get('depth')})")
    return "; ".join(parts) if parts else "none found"


def decision(report: dict) -> str:
    """The API's decision. Older APIs without one get a conservative mapping from the verdict."""
    d = report.get("decision")
    if d:
        return d
    v = report.get("verdict")
    if v == "NO LIENS FOUND":
        return "ALLOW"
    return "CONDITIONS" if v in ("LIENS", "CLOUDED", "UNKNOWN") else "N/A"


def why(report: dict) -> str:
    return report.get("why") or report.get("reason") or ""


def decision_line(report: dict) -> str:
    use = report.get("use") or "commercial"
    return f"Decision for {use} use: {decision(report)}. {why(report)}".strip()


def headline(report: dict) -> str:
    return f"{report.get('model')}: {report.get('verdict')}. {report.get('reason', '')}".strip()


def ruling_line(r: dict) -> str:
    out = f"{r.get('effect')} {r.get('scope')} {r.get('target')} for {r.get('use')} use [{r.get('id')}]: {r.get('note')}"
    if r.get("conditions"):
        out += f" Conditions: {r['conditions']}."
    if r.get("by"):
        out += f" By {r['by']}"
        out += f", {r['at']}." if r.get("at") else "."
    return out


def org_lines(report: dict) -> list[str]:
    """What the org's rulings changed, if a ruleset was applied."""
    org = report.get("org")
    if not org:
        return []
    applied, skipped = org.get("applied") or [], org.get("not_applied") or []
    head = f"Org rulings ({org.get('org')}): {org.get('decision_before')} -> {org.get('decision_after')}"
    if not applied and not skipped:
        return [head + ". No ruling in this ruleset matches this model."]
    lines = [head]
    lines += [f"- applied: {ruling_line(r)} ({r.get('why')})" for r in applied]
    lines += [f"- not applied: {ruling_line(r)} ({r.get('why')})" for r in skipped]
    return lines


def rulings(data: dict) -> str:
    rows = data.get("rulings") or []
    if not rows:
        return f"Ruleset {data.get('ruleset')}: no rulings yet."
    lines = [f"Ruleset {data.get('ruleset')} (graph {data.get('graph')}): {len(rows)} ruling{'s' if len(rows) != 1 else ''}"]
    for r in rows:
        tail = f" (superseded by {r['superseded_by']})" if r.get("superseded_by") else ""
        lines.append(f"- {ruling_line(r)}{tail}")
    return "\n".join(lines)


def summary(report: dict) -> str:
    """Decision and why first, then org rulings, verdict, declared license, liens and obligations."""
    lines = [decision_line(report), *org_lines(report), headline(report)]
    if report.get("detail"):
        lines.append(report["detail"])
    lines.append(f"Declared license: {_lic(report.get('declared_license'))}")
    anc = report.get("ancestors") or []
    if anc:
        known = sum(1 for a in anc if a.get("license") not in UNKNOWN_LICENSES)
        lines.append(f"Coverage: {known} of {len(anc)} ancestor{'s declare' if len(anc) != 1 else ' declares'} a license "
                     f"({report.get('coverage', 0):.0%})")
    if report.get("downloads_30d") is not None:
        lines.append(f"Downloads (30 days): {report['downloads_30d']:,}")
    liens = report.get("liens") or []
    if liens:
        lines.append("")
        lines.append("Liens:")
        for lien in liens:
            where = ("declared on the model itself" if lien.get("depth", 0) == 0
                     else f"inherited from {lien.get('via')} at depth {lien.get('depth')}")
            lines.append(f"- {lien.get('family')} ({lien.get('license')}), {lien.get('tier')}, {where}")
        lines.append("")
        lines.append("Obligations:")
        for lien in liens:
            for c in lien.get("clauses") or []:
                lines.append(f"- [{c.get('code')}] {c.get('obligation')}")
                if c.get("quote"):
                    lines.append(f'  Clause text: "{c["quote"]}" ({c.get("source", "")})')
    if report.get("verdict") == "UNKNOWN":
        lines.append("")
        lines.append("UNKNOWN is not a pass: FinePrint could not establish this model's lineage or license.")
    lines.append("")
    lines.append(report.get("disclaimer") or DISCLAIMER)
    return "\n".join(lines)


def path_line(p: dict) -> str:
    models = p.get("models") or []
    lics = p.get("licenses") or []
    rels = p.get("relations") or []
    if not models:
        return "(empty path)"
    out = f"{models[0]} [{_lic(lics[0] if lics else None)}]"
    for i in range(1, len(models)):
        rel = REL.get(rels[i - 1], rels[i - 1].lower()) if i - 1 < len(rels) else "->"
        lic = lics[i] if i < len(lics) else None
        out += f" --{rel}--> {models[i]} [{_lic(lic)}]"
    return out


def paths(report: dict) -> str:
    """Every proof path, one per line, grouped by lien."""
    lines = [headline(report), ""]
    liens = report.get("liens") or []
    if not liens:
        anc = report.get("ancestors") or []
        if anc:
            lines.append("No lien reaches this model. Declared ancestors:")
            for a in sorted(anc, key=lambda a: a.get("depth", 0)):
                lines.append(f"- depth {a.get('depth')}: {a.get('id')} [{_lic(a.get('license'))}]")
        else:
            lines.append("No declared ancestors, so there is no path to explain.")
        lines.append("")
        lines.append(report.get("disclaimer") or DISCLAIMER)
        return "\n".join(lines)
    for lien in liens:
        ps = lien.get("paths") or []
        if lien.get("depth", 0) == 0:
            lines.append(f"{lien.get('family')} ({lien.get('license')}): declared on the model itself, no path needed.")
            lines.append("")
            continue
        lines.append(f"{lien.get('family')} ({lien.get('license')}) arrives from {lien.get('via')} "
                     f"at depth {lien.get('depth')} by {len(ps)} path{'s' if len(ps) != 1 else ''}:")
        for i, p in enumerate(ps, 1):
            lines.append(f"  {i}. {path_line(p)}")
        if not ps:
            lines.append("  (the API returned no path rows for this lien)")
        lines.append("")
    lines.append("Each edge is a base_model declaration on the Hub. " + (report.get("disclaimer") or DISCLAIMER))
    return "\n".join(lines)


def downstream(model_id: str, data: dict, report: dict | None = None) -> str:
    st = data.get("stats") or {}
    top = data.get("top") or []
    lines = [f"{data.get('model', model_id)}: {st.get('count', 0):,} descendants, "
             f"deepest chain {st.get('deepest', 0)}, {st.get('downloads', 0):,} downloads (30 days) across them."]
    restricted = None
    if report and report.get("liens"):
        restricted = {l.get("license") for l in report["liens"]}
        lines.append(f"This model carries {', '.join(sorted(r for r in restricted if r))}; "
                     "descendants inherit those terms through it.")
    if top:
        lines.append("")
        lines.append(f"Top {len(top)} descendants by downloads:")
        permissive_count = 0
        for d in top:
            lic = d.get("license")
            flag = ""
            if restricted and lic in PERMISSIVE:
                permissive_count += 1
                flag = "  <- declared license differs from upstream terms"
            lines.append(f"- {d.get('id')} [{_lic(lic)}] depth {d.get('depth')}, "
                         f"{(d.get('downloads') or 0):,} downloads{flag}")
        if restricted:
            lines.append("")
            lines.append(f"{permissive_count} of these {len(top)} declare a permissive license.")
    else:
        lines.append("No descendants declare this model as a base.")
    return "\n".join(lines)


def remediation(report: dict) -> str:
    """Draft NOTICE text, model-card YAML and a checklist for the repo owner. Text only."""
    mid = report.get("model")
    verdict = report.get("verdict")
    liens = report.get("liens") or []
    out = [f"Draft remediation for {mid} (verdict: {verdict})",
           "Draft text only. FinePrint does not post, push or open anything on the Hub.", ""]

    if verdict == "UNKNOWN":
        out += ["FinePrint could not establish lineage or license for this model.",
                "Suggested model-card YAML front matter (fill in the real values):", "",
                "```yaml", "license: <license id, for example apache-2.0>",
                "base_model:", "- <org/name of the model this was trained from>", "```", "",
                DISCLAIMER]
        return "\n".join(out)
    if not liens:
        out += ["No liens found upstream, so no NOTICE or license change is suggested.",
                f"Declared license: {_lic(report.get('declared_license'))}. "
                f"Coverage: {report.get('coverage', 0):.0%}.", "", DISCLAIMER]
        return "\n".join(out)

    keys = []
    for l in liens:
        if l.get("license") not in keys:
            keys.append(l.get("license"))
    links = {l.get("license"): (l.get("clauses") or [{}])[0].get("source", "") for l in liens}

    # 1. NOTICE
    out += ["1. NOTICE file (add at the repo root)", "", "```text"]
    out.append(f"{mid}")
    out.append("")
    noticed = set()
    for l in liens:
        k = l.get("license")
        if k in noticed:
            continue
        noticed.add(k)
        if l.get("depth", 0) == 0:
            out.append(f"This model is distributed under the {l.get('family')} terms.")
        else:
            out.append(f"This model is derived from {l.get('via')}, which is distributed under the "
                       f"{l.get('family')} terms.")
        if k in NOTICE_TEXT:
            out.append(NOTICE_TEXT[k])
        elif l.get("family") == "CC BY-NC":
            out.append(f"Upstream material is licensed under {k.upper()} ({links.get(k)}). "
                       "Attribution is given above; use is limited to non-commercial purposes.")
        if links.get(k):
            out.append(f"Full terms: {links[k]}")
        out.append("")
    out += ["```", ""]

    # 2. LICENSE
    out += ["2. LICENSE file", ""]
    for k in keys:
        out.append(f"- Ship a full copy of the {k} terms ({links.get(k) or 'see upstream repo'}) "
                   f"as LICENSE, or as LICENSE-{k.upper()} next to your own LICENSE.")
    out.append("")

    # 3. Model card YAML
    bases = []
    for a in sorted(report.get("ancestors") or [], key=lambda a: a.get("depth", 0)):
        if a.get("depth") == 1 and a.get("id") not in bases:
            bases.append(a.get("id"))
    out += ["3. Model card YAML front matter", ""]
    out.append(f"Current declared license: {_lic(report.get('declared_license'))}.")
    out += ["", "```yaml"]
    if len(keys) == 1:
        out.append(f"license: {keys[0]}")
    else:
        out.append("license: other")
        out.append(f"license_name: {'-and-'.join(keys)}")
        out.append(f"license_link: LICENSE  # covers: {', '.join(keys)}")
    if bases:
        out.append("base_model:")
        out += [f"- {b}" for b in bases]
    out += ["```", ""]
    if report.get("declared_license") in PERMISSIVE and any(l.get("depth", 0) > 0 for l in liens):
        out.append(f"The card declares {report.get('declared_license')}, which differs from upstream terms. "
                   "If you want to offer your own changes under a different license, say that in the card "
                   "body and keep the YAML license matching the terms that cover the weights.")
        out.append("")

    # 4. Checklist
    out += ["4. Checklist from the clauses", ""]
    for lic, code, ob in obligations(report):
        out.append(f"- [ ] {ob} ({lic}, clause {code})")
    out += ["", DISCLAIMER]
    return "\n".join(out)


def _params(n: Any) -> str:
    if not isinstance(n, (int, float)) or n <= 0:
        return ""
    return f"{n / 1e9:.1f}B params" if n >= 1e9 else f"{n / 1e6:.0f}M params"


def substitutes(model_id: str, data: Any) -> str:
    items = data.get("substitutes") if isinstance(data, dict) else data
    if not isinstance(items, list):
        return f"Unexpected substitutes response for {model_id}: {data!r}"
    meta = data if isinstance(data, dict) else {}
    about = ", ".join(x for x in (meta.get("task"), _params(meta.get("params"))) if x)
    if not items:
        note = meta.get("note") or "No clean substitute found."
        return f"{model_id}{f' ({about})' if about else ''}: {note}"
    lines = [f"Clean substitutes for {model_id}{f' ({about})' if about else ''}:"]
    for s in items:
        if not isinstance(s, dict):
            lines.append(f"- {s}")
            continue
        bits = [x for x in (_params(s.get("params")),) if x]
        dl = s.get("downloads_30d", s.get("downloads"))
        if isinstance(dl, int):
            bits.append(f"{dl:,} downloads (30 days)")
        lines.append(f"- {s.get('id')} [{_lic(s.get('license'))}]" + (f", {', '.join(bits)}" if bits else ""))
    lines.append("")
    lines.append("Run check_model on a substitute before switching. " + DISCLAIMER)
    return "\n".join(lines)


def _n(x: Any) -> str:
    if isinstance(x, float) and x.is_integer():
        x = int(x)
    return f"{x:,}" if isinstance(x, (int, float)) and not isinstance(x, bool) else str(x)


def load_bearing(data: dict) -> str:
    top = data.get("top") or []
    lines = [f"Load-bearing base models by PageRank over lineage edges (top {len(top)}):"]
    for i, r in enumerate(top, 1):
        lines.append(f"{i}. {r.get('id')} [{_lic(r.get('license'))}] score {r.get('score', 0):.5f}, "
                     f"{_n(r.get('descendants', 0))} descendants with {_n(r.get('descendant_downloads_30d', 0))} "
                     f"downloads (30 days); own downloads {_n(r.get('downloads_30d', 0))}")
    if data.get("note"):
        lines += ["", f"Note: {data['note']}"]
    if data.get("query"):
        lines.append(f"Computed in FalkorDB with `{data['query']}`"
                     + (f" in {data['seconds']} s." if data.get("seconds") is not None else "."))
    return "\n".join(lines)


def relicense_points(data: dict) -> str:
    top = data.get("top") or []
    lines = ["Relicense points: models that declare a permissive license directly on a parent with restricted "
             "terms. Mismatched models below them inherit the difference.",
             f"- relicense points: {_n(data.get('relicensing_points', '?'))}",
             f"- points with mismatched descendants: {_n(data.get('points_with_mismatched_descendants', '?'))}",
             f"- mismatched models below some point: {_n(data.get('mismatched_models_below_some_point', '?'))}",
             "", f"Top {len(top)} by mismatched models below:"]
    for i, r in enumerate(top, 1):
        parents = ", ".join(r.get("restricted_parents") or []) or "?"
        lines.append(f"{i}. {r.get('model')} (restricted parent: {parents}): {_n(r.get('mismatched_models_below', 0))} "
                     f"mismatched models below with {_n(r.get('their_downloads_30d', 0))} downloads (30 days); "
                     f"own downloads {_n(r.get('own_downloads_30d', 0))}")
    lines += ["", "Declared license differs from upstream terms at each point. " + DISCLAIMER]
    return "\n".join(lines)


def what_if(data: dict) -> str:
    b, a = data.get("before") or {}, data.get("after") or {}
    lic = data.get("from_license") or "the restricted license"
    lines = [f"What if: {data.get('scenario', '?')}",
             f"Family: {_n(data.get('family_models', '?'))} models, {_n(data.get('family_edges', '?'))} lineage edges.",
             "", "| | before | after |", "|---|---|---|"]
    labels = {"models_under_nc_license": "declare the non-commercial license",
              "models_under_restricted": f"declare {lic}",
              "models_below_one": f"only inherit it from below a model under {lic}" if data.get("from_license")
              else "only inherit it from below a non-commercial model",
              "affected_total": f"bound by {lic} terms in total" if data.get("from_license")
              else "bound by non-commercial terms in total"}
    for k in dict.fromkeys(list(b) + list(a)):
        lines.append(f"| {labels.get(k, k)} | {_n(b.get(k, '-'))} | {_n(a.get(k, '-'))} |")
    if data.get("why"):
        lines += ["", data["why"]]
    relabel = data.get("relabel_needed") or []
    if relabel:
        lines += ["", "Most downloaded models that would still need to relabel:"]
        lines += [f"- {r.get('id')} [{r.get('license')}], {_n(r.get('downloads') or 0)} downloads" for r in relabel[:10]]
    graphs = data.get("graphs")
    if isinstance(graphs, dict):
        lines.append(f"Graphs: copied {graphs.get('family')} to {graphs.get('copy')} with GRAPH.COPY, edited the copy, "
                     "then deleted it (hub is not changed).")
    elif graphs:
        lines.append(f"Graphs: {', '.join(graphs)} (the original graph is not changed).")
    secs = data.get("seconds")
    if isinstance(secs, dict):
        lines.append("Timings (s): " + ", ".join(f"{k} {v}" for k, v in secs.items()))
    return "\n".join(lines)


