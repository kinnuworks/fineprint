def hub_stats(data: dict) -> str:
    lines = ["Hub-wide numbers" + (f" (computed in {data['computed_in']})" if data.get("computed_in") else "") + ":"]
    for k, v in data.items():
        if k == "computed_in" or isinstance(v, (dict, list)) or v is None:
            continue
        lines.append(f"- {STAT_LABELS.get(k, k.replace('_', ' '))}: {_n(v)}")
    return "\n".join(lines)


def search(q: str, rows: list, decisions: dict | None = None) -> str:
    if not rows:
        return f"No models match {q!r}."
    lines = [f"Models matching {q!r}, most downloaded first:"]
    for r in rows:
        line = f"- {r.get('id')} [{_lic(r.get('license'))}], {_n(r.get('downloads') or 0)} downloads"
        d = (decisions or {}).get(r.get("id"))
        if d is not None:
            line += f": {decision(d)}. {why(d)}" if d.get("verdict") != "ERROR" else f": not checked ({d.get('why')})"
        lines.append(line)
    return "\n".join(lines)
