export const verdictKey = (v: Verdict | string) =>
  v === "NO LIENS FOUND" ? "allow" : v === "LIENS" ? "cond" : v === "CLOUDED" ? "block" : "unknown";

/** CSS class for a license chip. */
export const licClass = (license: string | null | undefined, restrictiveSet?: Set<string>) => {
  const c = licenseClass(license, restrictiveSet);
  return `lic lic--${c === "restrictive" ? "restricted" : c}`;
};

