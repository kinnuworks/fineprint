/** Relation as it reads between two hops of a proof path ("A finetune of B"). */
export const relationPhrase = (r: string) => (r && r !== "..." ? (PHRASE[r] ?? relationLabel(r)) : "from");

/**
 * Relations aligned to hops: entry i links models[i] to models[i + 1].
 * Some paths carry extra leading entries or "..." placeholders; those are dropped or left blank.
 */
export function hopRelations(p: { models: string[]; relations?: string[] }): string[] {
  const n = Math.max(p.models.length - 1, 0);
  const rel = p.relations ?? [];
  const aligned = rel.length > n ? rel.slice(rel.length - n) : rel;
  return Array.from({ length: n }, (_, i) => (aligned[i] && aligned[i] !== "..." ? aligned[i] : ""));
}

export const relationLabel = (r: string) => RELATION[r] ?? r.toLowerCase().replace(/_/g, " ");

export const decisionKey = (d: string | undefined) =>
  d === "ALLOW" ? "allow" : d === "CONDITIONS" ? "cond" : d === "BLOCK" ? "block" : "unknown";

/** Decision as shown: an UNKNOWN verdict reads "Review first" so it never looks like a go-ahead. */
export function decisionView(
  decision: string | undefined,
  verdict: string,
): { label: string; key: string; hint?: string } | null {
  if (!decision) return null;
  if (verdict === "UNKNOWN" && decision !== "BLOCK")
    return {
      label: "Review first",
      key: "cond",
      hint: `${decision} in the API: lineage unknown`,
    };
  return { label: DECISION_LABEL[decision] ?? decision, key: decisionKey(decision) };
}

/** A quote reads as prose when it is not a markdown table row. */
export const isProse = (q: string) => !/^\s*\|/.test(q) && !q.includes("| [");

/**
 * Middle-truncates a model id for a graph label, keeping the org/ prefix and the end:
 * "hi-ft/research_release-v2" -> "hi-ft/…release-v2".
 */
export function midTrim(id: string, max: number): string {
  if (id.length <= max) return id;
  const slash = id.indexOf("/");
  let org = slash > 0 ? id.slice(0, slash + 1) : "";
  if (org.length > max / 2) org = org.slice(0, Math.max(3, Math.floor(max / 2) - 2)) + "…/";
  const tail = Math.max(6, max - org.length - 1);
  return org + "…" + id.slice(-tail);
}

