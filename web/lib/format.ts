/** Rough class of a Hub license key, used only for colouring the graph. */
export function licenseClass(license: string | null | undefined, restrictiveSet?: Set<string>): LicenseClass {
  if (!license) return "unknown";
  const l = license.toLowerCase();
  if (restrictiveSet?.has(l)) return "restrictive";
  if (l === "other" || l === "unknown") return "unknown";
  if (RESTRICTIVE.some((r) => r.test(l))) return "restrictive";
  if (PERMISSIVE.some((r) => r.test(l))) return "permissive";
  return "unknown";
}

