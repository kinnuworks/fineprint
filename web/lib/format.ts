/** Path parts that follow a model id in Hub URLs (huggingface.co/gpt2/tree/main). */
export const HUB_TAILS = new Set([
  "tree",
  "blob",
  "resolve",
  "raw",
  "discussions",
  "commits",
  "commit",
  "edit",
  "settings",
  "files",
  "community",
]);

/** Accepts a Hub URL, a FinePrint URL or a bare id and returns "org/name" or "name". */
export function normalizeId(input: string): string {
  let s = input.trim();
  s = s
    .replace(/^https?:\/\//, "")
    .replace(/^(www\.)?huggingface\.co\//, "")
    .replace(/^hf\.co\//, "");
  s = s.replace(/^[^/]*\.(app|com|dev|io|net|org|test|localhost)(:\d+)?\//, "");
  s = s.replace(/^localhost(:\d+)?\//, "");
  s = s.split(/[?#]/)[0].replace(/\/+$/, "");
  const parts = s.split("/").filter(Boolean);
  if (parts.length > 1 && HUB_TAILS.has(parts[1])) return parts[0];
  return parts.slice(0, 2).join("/");
}
